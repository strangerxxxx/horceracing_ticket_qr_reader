import 'package:flutter_test/flutter_test.dart';
import 'package:horceracing_ticket_qr_reader/ticket_qr_parse.dart';

void main() {
  Map purchaseOf(String paste) {
    final result = parseTicketFromPastedText(paste)!;
    return (result['購入内容'] as List).first as Map;
  }

  test('JRA 3連単 3着ながし', () {
    final purchase = purchaseOf(
      '00000001056789012345678901234567890123456789012345678901234567890123456789012345678901234560533\n'
      '50600226040709201352702665944234300180792596000010010000000000000010010000000000000000000010000',
    );
    expect(purchase['ながし'], '3着ながし');
    expect(purchase['馬番'], [
      [5, 8],
      [5, 8],
      [11],
    ]);
  });

  test('JRA 3連単 1・3着ながし (14>6>11)', () {
    final purchase = purchaseOf(
      '00000001056789012345678901234567890123456789012345678901234567890123456789012345678901234560516\n'
      '50600226040709201352710361654234300180937293000000000000010000000001000000000000000000000010000',
    );
    expect(purchase['ながし'], '1・3着ながし');
    expect(purchase['馬番'], [
      [14],
      [6],
      [11],
    ]);
  });

  test('JRA 3連単 1・3着ながし (2>11>1)', () {
    final purchase = purchaseOf(
      '00000001056789012345678901234567890123456789012345678901234567890123456789012345678901234560498\n'
      '50600226040710201332217333404234300182028793010000000000000000000000000010000000100000000000000',
    );
    expect(purchase['ながし'], '1・3着ながし');
    expect(purchase['馬番'], [
      [2],
      [11],
      [1],
    ]);
  });

  test('JRA 3連単 1・2着ながし', () {
    final purchase = purchaseOf(
      '50600226040711201332203553154234300182016491000000000010000000000000001000000000000000110000000\n'
      '00000001056789012345678901234567890123456789012345678901234567890123456789012345678901234560493',
    );
    expect(purchase['ながし'], '1・2着ながし');
  });

  test('JRA 3連単 1着ながし', () {
    final purchase = purchaseOf(
      '50600226040711201332193383354234300182004694000000000010000000000000111000000000000000111000000\n'
      '00000001056789012345678901234567890123456789012345678901234567890123456789012345678901234560509',
    );
    expect(purchase['ながし'], '1着ながし');
  });

  test('JRA 3連単 2着ながし', () {
    final purchase = purchaseOf(
      '00000001056789012345678901234567890123456789012345678901234567890123456789012345678901234560503\n'
      '50600226040710201332230290474234300182041995010000000010000000100000000000000000010000000010000',
    );
    expect(purchase['ながし'], '2着ながし');
  });

  test('JRA 3連単 2・3着ながし (11>2>1)', () {
    final purchase = purchaseOf(
      '00000001056789012345678901234567890123456789012345678901234567890123456789012345678901234560490\n'
      '50600226040710201332225431414234300182030892000000000010000000010000000000000000100000000000000',
    );
    expect(purchase['ながし'], '2・3着ながし');
    expect(purchase['馬番'], [
      [11],
      [2],
      [1],
    ]);
  });
}
